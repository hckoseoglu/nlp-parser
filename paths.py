"""Where the project's files are, and a helper to read them."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent

GRAMMAR_FILE = ROOT / "grammar" / "grammar.txt"        # the grammar as we write it
CNF_FILE = ROOT / "grammar" / "grammar_cnf.txt"        # the same grammar in Chomsky Normal Form (generated by to_cnf.py)
TAGS_FILE = ROOT / "grammar" / "tags.txt"              # lexicon, part 1: features that follow from the tag
STEMS_FILE = ROOT / "grammar" / "stems.txt"            # lexicon, part 2: features of the stem
LEXICON_FILE = ROOT / "grammar" / "lexicon.txt"        # lexicon, part 3: the word forms
TESTS_FILE = ROOT / "data" / "tests.txt"
GOLD_FILE = ROOT / "data" / "sentences.md"


def data_lines(path):
    """The lines of a data file without comments and blank lines."""
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].rstrip()
        if line.strip():
            yield line
